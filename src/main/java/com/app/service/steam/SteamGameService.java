package com.app.service.steam;


import java.util.List;

import com.app.dto.steam.SteamGame;

/**
 * ================================================================
 * SteamGameService
 * ================================================================
 *
 * 메인 페이지에서 사용할 Steam 게임 데이터를 제공하는 Service 인터페이스.
 *
 * Controller에서는 Steam API를 직접 호출하지 않고
 * 이 Service를 통해 Steam 게임 데이터를 가져온다.
 *
 * 실제 Steam API 호출 및 데이터 가공은
 * SteamGameServiceImpl에서 담당한다.
 */
public interface SteamGameService {

    /**
     * ============================================================
     * Steam 할인 게임 조회
     * ============================================================
     *
     * Steam에서 현재 할인 중인 게임들을 조회한다.
     *
     * 메인 페이지에서는 이 데이터를 이용해서
     *
     * [Steam 할인 게임]
     * [게임] [게임] [게임]
     * [게임] [게임] [게임]
     *
     * 형태로 최대 6개를 보여준다.
     *
     * @return Steam 할인 게임 목록
     */
    List<SteamGame> getDiscountGames();


    /**
     * ============================================================
     * Steam 랜덤 게임 조회
     * ============================================================
     *
     * Steam 게임 목록 중에서 랜덤하게 게임을 선택한다.
     *
     * 메인 페이지에서는 이 데이터를 이용해서
     *
     * [Steam 랜덤 게임]
     * [게임] [게임] [게임]
     * [게임] [게임] [게임]
     *
     * 형태로 최대 6개를 보여준다.
     *
     * @return 랜덤으로 선택된 Steam 게임 목록
     */
    List<SteamGame> getRandomGames();
}